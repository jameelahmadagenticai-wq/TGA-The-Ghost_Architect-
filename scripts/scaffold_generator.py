import os
import json
import subprocess

# ==============================
# PATH FIX
# ==============================
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

OUTPUT_DIR = os.path.join(BASE_DIR, "generated_project")
BLUEPRINT_PATH = os.path.join(BASE_DIR, "output", "blueprint.json")
MANIFESTO_PATH = os.path.join(BASE_DIR, "output", "ARCHITECTS_MANIFESTO.md")


# ==============================
# LOAD BLUEPRINT
# ==============================
def load_blueprint():
    if not os.path.exists(BLUEPRINT_PATH):
        raise FileNotFoundError("❌ blueprint.json not found")

    with open(BLUEPRINT_PATH, "r", encoding="utf-8") as f:
        return json.load(f)


# ==============================
# SAFE FILE CREATOR
# ==============================
def create_file(path, content=""):
    os.makedirs(os.path.dirname(path), exist_ok=True)

    with open(path, "w", encoding="utf-8") as f:
        f.write(content)


# ==============================
# TEMPLATE: FASTAPI
# ==============================
def fastapi_template(service_name):
    return f"""
from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware

app = FastAPI(title="{service_name}")

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

@app.get("/health")
def health():
    return {{"status": "ok", "service": "{service_name}"}}

@app.get("/")
def root():
    return {{"message": "Welcome to {service_name}"}}
"""


# ==============================
# TEMPLATE: DOCKERFILE
# ==============================
def dockerfile_template():
    return """
FROM python:3.11-slim

WORKDIR /app

COPY requirements.txt .

RUN pip install --no-cache-dir -r requirements.txt

COPY . .

EXPOSE 8000

CMD ["uvicorn", "main:app", "--host", "0.0.0.0", "--port", "8000"]
"""


# ==============================
# TEMPLATE: REQUIREMENTS
# ==============================
def requirements_template():
    return """
fastapi
uvicorn
pydantic
"""


# ==============================
# TEMPLATE: DOCKER COMPOSE
# ==============================
def docker_compose_template(services):
    compose = "version: '3.9'\nservices:\n"

    port = 8001

    for service in services:
        compose += f"""
  {service}:
    build: ./{service}
    ports:
      - "{port}:8000"
    environment:
      - ENV=development
    networks:
      - app-network
"""
        port += 1

    compose += """
networks:
  app-network:
    driver: bridge
"""
    return compose


# ==============================
# TEMPLATE: GITIGNORE
# ==============================
def gitignore_template():
    return """
__pycache__/
*.pyc
.env
.venv/
node_modules/
"""


# ==============================
# GIT SETUP
# ==============================
def run_git_setup(project_path, repo_url=None):
    logs = []

    def run_cmd(cmd):
        result = subprocess.run(
            cmd,
            cwd=project_path,
            capture_output=True,
            text=True,
            shell=True
        )
        logs.append(f"$ {' '.join(cmd)}\n{result.stdout}\n{result.stderr}")
        return result

    try:
        run_cmd(["git", "init"])
        run_cmd(["git", "branch", "-M", "main"])
        run_cmd(["git", "add", "."])
        run_cmd([
            "git", "commit",
            "-m", "Initial scaffold generated by The Ghost Architect"
        ])

        if repo_url:
            run_cmd(["git", "remote", "add", "origin", repo_url])
            run_cmd(["git", "push", "-u", "origin", "main"])

    except Exception as e:
        logs.append(f"❌ Git error: {str(e)}")

    return "\n".join(logs)


# ==============================
# GENERATE PROJECT
# ==============================
def generate_project():
    blueprint = load_blueprint()

    print("📦 Generating project...")

    # Clean old project
    if os.path.exists(OUTPUT_DIR):
        import shutil
        shutil.rmtree(OUTPUT_DIR)

    os.makedirs(OUTPUT_DIR, exist_ok=True)

    services = []

    for name, value in blueprint.items():
        path = os.path.join(OUTPUT_DIR, name)

        # =========================
        # SERVICE (folder)
        # =========================
        if isinstance(value, dict):
            services.append(name)

            os.makedirs(path, exist_ok=True)

            create_file(os.path.join(path, "main.py"), fastapi_template(name))
            create_file(os.path.join(path, "Dockerfile"), dockerfile_template())
            create_file(os.path.join(path, "requirements.txt"), requirements_template())
            create_file(os.path.join(path, "README.md"), f"# {name}\n\nGenerated by TGA\n")

        # =========================
        # IGNORE ROOT FILES FROM BLUEPRINT
        # =========================
        elif isinstance(value, str):
            continue

    # =========================
    # ROOT FILES
    # =========================
    create_file(
        os.path.join(OUTPUT_DIR, "docker-compose.yml"),
        docker_compose_template(services)
    )

    create_file(
        os.path.join(OUTPUT_DIR, ".gitignore"),
        gitignore_template()
    )

    create_file(
        os.path.join(OUTPUT_DIR, ".env.example"),
        "ENV=development\n"
    )

    # =========================
    # MANIFESTO
    # =========================
    if os.path.exists(MANIFESTO_PATH):
        with open(MANIFESTO_PATH, "r", encoding="utf-8") as f:
            manifesto = f.read()

        create_file(
            os.path.join(OUTPUT_DIR, "ARCHITECTS_MANIFESTO.md"),
            manifesto
        )

    # =========================
    # GIT SETUP (FINAL STEP)
    # =========================
    git_logs = run_git_setup(OUTPUT_DIR)

    print("✅ Project generated successfully!")
    print("\n📜 Git Logs:\n")
    print(git_logs)


# ==============================
# RUN
# ==============================
if __name__ == "__main__":
    generate_project()